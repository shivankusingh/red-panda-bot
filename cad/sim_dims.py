"""Print the sim robot's dimensions as Onshape variables and write cad/variables.md.

The CAD skeleton should use the same numbers the policies were trained on. Read straight
from the model the walking env builds (sim/red_panda.xml + model_config: legs x0.7, home pose),
so this table can't drift from the sim. If the CAD has to change a number, change it in the
sim too and retrain.

  python cad/sim_dims.py
"""
import sys
from pathlib import Path

import mujoco
import numpy as np

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "sim"))
import red_panda_walk as rpw  # noqa: E402

m = rpw._robot_spec(rpw.default_config()).compile()
d = mujoco.MjData(m)
d.qpos[:] = m.key_qpos[m.key("home").id]
mujoco.mj_kinematics(m, d)
mm = lambda x: round(1000 * float(x), 2)  # noqa: E731


def body_pos(name):
  return m.body_pos[m.body(name).id]


def capsule_len(body):
  g = [i for i in range(m.ngeom) if m.geom_bodyid[i] == m.body(body).id
       and m.geom_type[i] == mujoco.mjtGeom.mjGEOM_CAPSULE][0]
  return 2 * m.geom_size[g][1]


def joint_deg(name):
  return float(np.degrees(d.qpos[m.jnt_qposadr[m.joint(name).id]]))


torso = m.geom_size[m.geom("torso").id]
foot_r = m.geom_size[m.geom("fl_foot").id][0]
q = d.qpos[3:7]
pitch = float(np.degrees(2 * np.arctan2(q[2], q[0])))  # + = nose down

rows = [  # (Onshape variable, value mm/deg, what it is)
  ("#torso_len", mm(2 * torso[0]), "torso box length (front-back)"),
  ("#torso_wid", mm(2 * torso[1]), "torso box width"),
  ("#torso_ht", mm(2 * torso[2]), "torso box height"),
  ("#hip_x", mm(body_pos("fl_hip")[0]), "hip axes ahead of / behind the torso centre (front +, hind -)"),
  ("#hip_side_y", mm(body_pos("fl_hip")[1]), "hip-side (abduction) axis out from the centre line, at torso mid-height"),
  ("#leg_plane_y", mm(body_pos("fl_hip")[1] + body_pos("fl_upper")[1]),
   "hip pitch axis / leg plane out from the centre line (hip_side_y + 30 mm offset)"),
  ("#thigh", mm(capsule_len("fl_upper")), "hip axis to knee axis"),
  ("#shin", mm(capsule_len("fl_lower")), "knee axis to foot ball CENTRE"),
  ("#foot_r", mm(foot_r), "foot ball radius (the floor touches the ball, so foot tip = shin + foot_r)"),
  ("#tail_base_x", mm(body_pos("tail_base")[0]), "tail wag axis, at the back face of the torso"),
  ("#tail_lift_dx", mm(-body_pos("tail_1")[0]), "tail wag axis to tail lift axis (backwards)"),
  ("#tail_seg1", mm(-body_pos("tail_2")[0]), "tail lift axis to mid-tail wag servo"),
  ("#tail_seg2", mm(capsule_len("tail_2")), "mid-tail wag axis to tail tip"),
  ("#neck_x", mm(body_pos("neck_1")[0]), "neck turn axis ahead of the torso centre"),
  ("#neck_z", mm(body_pos("neck_1")[2]), "neck turn axis base above the torso centre"),
  ("#neck_nod_dz", mm(body_pos("neck_2")[2]), "turn axis base to nod axis (up)"),
  ("#head_dx", mm(body_pos("head")[0]), "nod axis to head tilt axis (forward)"),
]

home = [
  ("torso centre height", f"{mm(d.qpos[2])} mm"),
  ("torso pitch", f"{pitch:.1f} deg nose-down"),
]
for leg, name in (("fl", "front"), ("bl", "hind")):
  hip, knee = joint_deg(f"{leg}_hip"), joint_deg(f"{leg}_knee")
  # MuJoCo +hip swings the foot backward; thigh angle reported from straight down, forward +,
  # relative to the TORSO (the torso itself is pitched nose-down by the amount above).
  home.append((f"{name} thigh (from torso-down, forward +)", f"{-hip:.1f} deg"))
  home.append((f"{name} knee bend (0 = straight)", f"{abs(knee):.1f} deg"))

ranges = [(j, *np.degrees(m.jnt_range[m.joint(j).id])) for j in
          ("fl_hip_side", "fl_hip", "fl_knee", "bl_knee", "tail_wag", "tail_lift", "tail_wag2",
           "neck_turn", "neck_nod", "head_tilt")]

lines = ["# Onshape variables from the sim", "",
         "Generated by `python cad/sim_dims.py` from the model the policies were trained on. "
         "Paste these into an Onshape Variable Studio and build the skeleton sketch from them. "
         "If CAD needs a different number, change the sim too and retrain.", "",
         "Frame: x forward, y left, z up, origin at the torso centre (same as the sim).", "",
         "| Variable | Value (mm) | Meaning |", "|---|---|---|"]
lines += [f"| `{v}` | {x} | {w} |" for v, x, w in rows]
lines += ["", "## Standing (home) pose", "", "| | |", "|---|---|"]
lines += [f"| {k} | {v} |" for k, v in home]
lines += ["", "## Sim joint limits (deg)", "",
          "Rough limits from the box model. What the policies actually use is narrower "
          "(see `runs/<down run>/chain/legs.json`); design the knee for at least 0-110 deg.", "",
          "| Joint | min | max |", "|---|---|---|"]
lines += [f"| {j} | {lo:.0f} | {hi:.0f} |" for j, lo, hi in ranges]
lines += ["", f"Total mass in the sim: {sum(m.body_mass):.2f} kg (nominal; training randomizes +/-10%).", ""]

text = "\n".join(lines)
print(text)
(REPO / "cad" / "variables.md").write_text(text)
print(f"-> {REPO / 'cad' / 'variables.md'}")
